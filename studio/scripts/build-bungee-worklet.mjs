// Builds public/iv-bungee-processor.js: Bungee's Emscripten glue (with the embedded WASM) from
// bungee-pitch-shift, patched to export _malloc/_free/HEAPF32, plus our own AudioWorklet processor.
// Works on bytes so the embedded binary string is not re-encoded.
import {existsSync, mkdirSync, readFileSync, writeFileSync} from 'node:fs'
import {createRequire} from 'node:module'
import {dirname, join} from 'node:path'
import {fileURLToPath} from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
const out = join(root, 'public', 'iv-bungee-processor.js')

export function buildBungeeWorklet() {
  let pkg
  try {
    // The package's `exports` map hides package.json, so resolve the main entry (dist/index.js).
    pkg = dirname(dirname(require.resolve('bungee-pitch-shift')))
  } catch {
    if (existsSync(out)) return out
    throw new Error('bungee-pitch-shift is not installed; cannot build iv-bungee-processor.js')
  }
  const bundle = readFileSync(join(pkg, 'dist/bungee-processor-bundled.js'))
  const marker = Buffer.from('/* ===== AUDIOWORKLET PROCESSOR ===== */')
  const cut = bundle.indexOf(marker)
  if (cut < 0) throw new Error('Unexpected bungee-processor-bundled.js layout (processor marker missing)')
  let glue = bundle.subarray(0, cut)
  const replace = (from, to) => {
    const a = Buffer.from(from)
    const at = glue.indexOf(a)
    if (at < 0 || glue.indexOf(a, at + 1) >= 0) throw new Error('Bungee glue patch anchor not unique: ' + from)
    glue = Buffer.concat([glue.subarray(0, at), Buffer.from(to), glue.subarray(at + a.length)])
  }
  // Expose the allocator and a live heap view; Emscripten built this module without them.
  replace(
    'wasmExports=await (createWasm());run();',
    'wasmExports=await (createWasm());Module["_malloc"]=_malloc;Module["_free"]=_free;Object.defineProperty(Module,"HEAPF32",{get:()=>HEAPF32});run();',
  )
  replace('export default createBungeeModule;', '')
  const processor = readFileSync(join(root, 'worklets', 'iv-bungee-processor.src.js'))
  const header = Buffer.from('/* AUTO-GENERATED by studio/scripts/build-bungee-worklet.mjs from bungee-pitch-shift. Do not edit. */\n')
  mkdirSync(dirname(out), {recursive: true})
  writeFileSync(out, Buffer.concat([header, glue, Buffer.from('\n'), processor]))
  return out
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  console.log('built', buildBungeeWorklet())
}
